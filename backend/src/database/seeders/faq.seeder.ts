import { Injectable, OnModuleInit, Logger } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { Faq } from 'src/modules/faq/entities/faq.entity';

@Injectable()
export class FaqSeeder implements OnModuleInit {
  private readonly logger = new Logger(FaqSeeder.name);

  constructor(
    @InjectRepository(Faq)
    private readonly faqRepository: Repository<Faq>,
  ) {}

  async onModuleInit() {
    const faqSeedData = [
        {
            question: 'I can access my other account but one of my accounts is suspended. What are the common reasons for account suspension?',
            answer: 'Accounts are typically suspended for policy violations, unusual login patterns, security breaches, spam activities, or fraudulent behavior. Each account is evaluated independently based on its activity history.',
            category: 'Account',
           },
           {
            question: 'Can I receive my completed itinerary via email for offline access?',
            answer: 'Yes, you can email your itinerary to yourself or others directly from the platform. This allows you to access your travel plans offline, share with companions, and have a backup copy for your trip.',
            category: 'Itinerary',
           },
           {
             question: 'How does the trip length recommendation feature work?',
             answer: 'Our trip length guide analyzes your destination and selected activities to recommend optimal trip duration. Enter your destination and preferences to receive personalized recommendations for the ideal trip length.',
             category: 'Planning',
           },
           {
             question: 'Why should I pay for your AI travel features instead of planning myself?',
             answer: 'Our AI saves you 15-20 hours of research time by instantly generating personalized itineraries, optimized packing lists, and budget breakdowns. For example, planning a 10-day Europe trip manually takes weeks, but our AI delivers a comprehensive plan in minutes with local insights you might miss.',
             category: 'Value',
           },
           {
             question: 'Can your Budget-Based Planning feature handle complex multi-city trips?',
             answer: 'Yes, our AI allocates budgets across multiple destinations, considering varying costs between cities. For example, it will automatically assign more budget to expensive cities like London and optimize savings in cheaper destinations like Prague within the same European trip.',
             category: 'Budget',
           },
           {
            question: 'What makes your packing lists generator different from free travel apps?',
            answer: 'Our Smart Packing Lists use AI to analyze your specific destination weather, planned activities, local customs, and cultural considerations. Unlike generic apps, we provide personalized recommendations - for example, suggesting modest clothing for temple visits in Thailand or specific hiking gear for Patagonia treks based on your exact travel dates.',
            category: 'Packing',
           },
           {
            question: 'How detailed are the itineraries generated by your AI system?',
            answer: 'Our AI creates comprehensive day-by-day itineraries with specific timings, restaurant recommendations, transportation options, and activity bookings. For example, a Paris itinerary includes exact metro routes, restaurant reservation times, and museum skip-the-line ticket suggestions tailored to your preferences.',
            category: 'Itinerary',
           },
           {
            question: 'What customization options are available after generating an AI itinerary?',
            answer: 'You can fully customize any AI-generated itinerary by modifying activities, adjusting timings, swapping restaurants, changing accommodation types, and adding personal destinations. For instance, you can replace suggested art museums with adventure activities or extend stays in preferred cities.',
            category: 'Custom Itinerary',
           },
           
    ];

    for (const faq of faqSeedData) {
      const existing = await this.faqRepository.findOne({
        where: { question: faq.question },
      });

      if (!existing) {
        const newFaq = this.faqRepository.create(faq);
        await this.faqRepository.save(newFaq);
        this.logger.log(`[Seeder] Created FAQ: ${faq.question}`);
      } else {
        this.logger.log(`[Seeder] FAQ already exists: ${faq.question}. Skipping.`);
      }
    }

    this.logger.log('[Seeder] FAQs seeding completed.');
  }
}
